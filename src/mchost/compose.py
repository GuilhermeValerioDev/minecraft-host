"""Generate the compose file for an instance.

``instance.toml`` is the source of truth. The compose file next to it is
derived and will be overwritten, so users should never need to edit it.
"""

from __future__ import annotations

import os
from typing import Any

import yaml

from .config import Instance, java_for_mc
from .paths import Layout

HEADER = "# Generated by mchost. Edit instance.toml instead of this file.\n"

JAVA_TAGS = {
    8: "java8",
    11: "java11",
    17: "java17",
    21: "java21",
    25: "java25",
}

LOADER_VERSION_ENV = {
    "paper": "PAPER_BUILD",
    "fabric": "FABRIC_LOADER_VERSION",
    "quilt": "QUILT_LOADER_VERSION",
    "forge": "FORGE_VERSION",
    "neoforge": "NEOFORGE_VERSION",
}


def render_compose(instance: Instance, data_source: str = "./server") -> str:
    env: dict[str, str] = {
        "EULA": "TRUE" if instance.eula else "FALSE",
        "MEMORY": instance.memory.upper(),
        "TZ": instance.tz,
        "ENABLE_RCON": "true",
        "RCON_PASSWORD": instance.rcon_password,
    }
    if instance.motd:
        env["MOTD"] = instance.motd

    if instance.kind == "modpack" and instance.modpack is not None:
        pack = instance.modpack
        if pack.source == "local":
            # Local server packs are already extracted into the data directory.
            # Let itzg install the selected loader on top of the pack.
            resolved = pack.resolved
            loader = resolved.get("loader") or instance.loader
            mc_version = resolved.get("minecraft") or instance.mc_version
            env["TYPE"] = loader.upper()
            env["VERSION"] = mc_version
            loader_version = resolved.get("loader_version") or instance.loader_version
            if loader_version and loader in LOADER_VERSION_ENV:
                env[LOADER_VERSION_ENV[loader]] = loader_version
        elif pack.file_kind in ("zip", "tar"):
            env["GENERIC_PACK"] = f"/modpacks/{pack.file_name}"
            env["SKIP_GENERIC_PACK_UPDATE_CHECK"] = "true"
            resolved = pack.resolved
            loader = resolved.get("loader") or instance.loader
            mc_version = resolved.get("minecraft") or instance.mc_version
            env["TYPE"] = loader.upper()
            env["VERSION"] = mc_version
            loader_version = resolved.get("loader_version") or instance.loader_version
            if loader_version and loader in LOADER_VERSION_ENV:
                env[LOADER_VERSION_ENV[loader]] = loader_version
        else:
            env["TYPE"] = "MODRINTH"
            env["MODRINTH_MODPACK"] = f"/modpacks/{pack.file_name}"
    else:
        env["TYPE"] = instance.loader.upper()
        env["VERSION"] = instance.mc_version
        if instance.loader_version and instance.loader in LOADER_VERSION_ENV:
            env[LOADER_VERSION_ENV[instance.loader]] = instance.loader_version

    env.update({str(key): str(value) for key, value in instance.extra_env.items()})

    java = instance.java_version or java_for_mc(instance.mc_version)
    image = f"itzg/minecraft-server:{JAVA_TAGS.get(java, 'latest')}"

    ports = [
        f"{instance.port}:25565",
        # RCON should never be exposed beyond the host by default.
        f"127.0.0.1:{instance.rcon_port}:25575",
    ]
    if instance.bluemap_port is not None:
        ports.append(f"{instance.bluemap_port}:8100")

    volumes = [f"{data_source}:/data:Z"]
    if instance.kind == "modpack":
        volumes.append("./pack:/modpacks:ro")

    service: dict[str, Any] = {
        "image": image,
        "container_name": f"mc-{instance.slug}",
        "hostname": f"mc-{instance.slug}",
        "restart": "unless-stopped",
        "ports": ports,
        "environment": env,
        "volumes": volumes,
        "stdin_open": True,
        "tty": True,
        "healthcheck": {
            "test": ["CMD", "mc-health"],
            "interval": "30s",
            "timeout": "10s",
            "retries": 3,
            "start_period": "2m",
        },
    }

    document = {"services": {"minecraft": service}}
    return HEADER + yaml.safe_dump(
        document, sort_keys=False, default_flow_style=False, width=4096
    )


def write_compose(layout: Layout, instance: Instance) -> tuple[Any, bool]:
    """Write the generated compose file. Returns ``(path, changed)``."""
    path = layout.compose_file(instance.slug)
    path.parent.mkdir(parents=True, exist_ok=True)
    text = render_compose(instance, layout.compose_data_source(instance))
    changed = not path.is_file() or path.read_text(encoding="utf-8") != text
    if changed:
        tmp = path.with_name(path.name + ".tmp")
        tmp.write_text(text, encoding="utf-8")
        os.chmod(tmp, 0o600)
        os.replace(tmp, path)
    return path, changed
